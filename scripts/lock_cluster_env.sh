#!/usr/bin/env bash
# Re-resolve requirements/cluster-gpu.txt for Linux x86_64 (glibc >= 2.31, as
# the vLLM 0.12 wheels need) / Python 3.12.
# Needs a tau2 source checkout (TAU2_SRC) at the pinned commit so its
# dependencies are resolved together; tau2 and handoff lines are then removed
# because the setup job installs both editable without dependencies.
# Resolution only sees packages published before EXCLUDE_NEWER (default: the day
# after verl 0.8.0 was published), so re-running it gives the same lock. The
# project's own pin, hydra-core 1.3.7, is newer and is exempted.
set -euo pipefail
repo="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
: "${TAU2_SRC:?set TAU2_SRC to a tau2-bench checkout at the pinned commit}"
exclude_newer="${EXCLUDE_NEWER:-2026-06-02T00:00:00Z}"
tmp="$(mktemp)"
{ cat "${repo}/requirements/cluster-gpu.in"; echo "tau2 @ file://${TAU2_SRC}"; echo "handoff @ file://${repo}"; } > "${tmp}"
uv pip compile "${tmp}" --python-version 3.12 --python-platform x86_64-manylinux_2_31 \
  --exclude-newer "${exclude_newer}" \
  --exclude-newer-package "hydra-core=2026-09-30T00:00:00Z" \
  --no-header --no-annotate -o "${tmp}.out"
{
  echo "# Generated by scripts/lock_cluster_env.sh from requirements/cluster-gpu.in"
  echo "# Linux x86_64, Python 3.12, CUDA 12.8 wheels (torch 2.9.0, vLLM 0.12.0, verl 0.8.0)"
  echo "# PyPI snapshot: packages published before ${exclude_newer}"
  grep -v -E '^(tau2|handoff) @ ' "${tmp}.out"
} > "${repo}/requirements/cluster-gpu.txt"
rm -f "${tmp}" "${tmp}.out"
echo "wrote requirements/cluster-gpu.txt"
